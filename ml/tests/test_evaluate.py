"""Evaluation end to end on a miniature synthetic ShanghaiTech (no real test data is read)."""

import json
import shutil
from pathlib import Path

import pytest
import torch
from helpers import make_dataset_tree, tiny_cfg

from crowd.checkpoint import load_checkpoint, load_model, save_checkpoint
from crowd.evaluate import (
    AlreadyEvaluatedError,
    evaluate_run,
    main,
    worst_indices,
)
from crowd.train import fit

PNG = b"\x89PNG"


@pytest.fixture(scope="module")
def world(tmp_path_factory) -> Path:
    """Train one tiny run per part once; tests copy this tree so they cannot interfere."""
    base = tmp_path_factory.mktemp("world")
    for part in ("part_A", "part_B"):
        raw, processed, train_s, _ = make_dataset_tree(base, part, n_train=3, n_test=4)
        cfg = tiny_cfg(base, part=part, run_id=f"{part}-t", raw=raw, processed=processed)
        fit(cfg, train_s[:2], train_s[2:])
    return base


@pytest.fixture
def env(world, tmp_path) -> dict:
    """A private copy of the world plus an empty docs dir."""
    shutil.copytree(world, tmp_path / "w")
    base = tmp_path / "w"
    return {
        "base": base,
        "docs": tmp_path / "docs",
        "kw": {"raw": base / "raw", "processed": base / "processed", "device": "cpu", "workers": 0},
    }


def run_dir(env, part="part_A") -> Path:
    return env["base"] / "runs" / f"{part}-t"


def evaluate(env, part="part_A", **extra):
    return evaluate_run(run_dir(env, part), docs_dir=env["docs"], **env["kw"], **extra)


def test_test_split_writes_every_output(env):
    r = evaluate(env)
    results = env["docs"] / "results"
    for name in ("part_A.json", "part_A-scatter.png", "part_A-worst10.png"):
        assert (results / name).exists(), name
    assert (results / "part_A-scatter.png").read_bytes().startswith(PNG)
    assert (results / "part_A-worst10.png").read_bytes().startswith(PNG)
    assert json.loads((results / "part_A.json").read_text())["mae"] == r["mae"]
    assert (r["split"], r["n"], len(r["worst"])) == ("test", 4, 4)  # fewer than 10 images


def test_test_result_is_recorded_in_summary_and_published(env):
    r = evaluate(env)
    summary = json.loads((run_dir(env) / "summary.json").read_text())
    assert summary["test"]["mae"] == r["mae"] and summary["test"]["n"] == 4
    assert summary["test"]["checkpoint"] == "best.pth"
    published = json.loads((env["docs"] / "runs" / "part_A-t.json").read_text())
    assert published["summary"]["test"]["mae"] == r["mae"]


def test_results_md_is_generated_from_measured_numbers(env):
    r = evaluate(env)
    md = (env["docs"] / "results.md").read_text()
    assert "Generated by `python -m crowd.evaluate`" in md
    assert f"{r['mae']:.1f}" in md and "part_A-t" in md
    assert "## Part A" in md and "Error by ground-truth count" in md
    assert "results/part_A-scatter.png" in md and "results/part_A-worst10.png" in md
    assert ("**missed**" in md) != r["acceptance"]["passed"]  # verdict matches the data


def test_results_md_aggregates_both_parts_in_order(env):
    evaluate(env, "part_B")
    evaluate(env, "part_A")
    md = (env["docs"] / "results.md").read_text()
    assert md.index("## Part A") < md.index("## Part B")
    assert "part_A-t" in md and "part_B-t" in md


def test_test_split_is_read_once_per_run(env):
    evaluate(env)
    with pytest.raises(AlreadyEvaluatedError, match="--force"):
        evaluate(env)
    again = evaluate(env, force=True)  # explicit override works
    assert again["n"] == 4


def test_cli_reports_refusal_as_a_clean_exit(env):
    argv = [str(run_dir(env)), "--raw", str(env["kw"]["raw"]), "--processed",
            str(env["kw"]["processed"]), "--docs", str(env["docs"]), "--device", "cpu",
            "--workers", "0"]  # fmt: skip
    main(argv)
    with pytest.raises(SystemExit, match="already evaluated"):
        main(argv)


def test_validation_dry_run_never_touches_test_outputs(env):
    r = evaluate(env, split="val")
    assert (r["split"], r["n"]) == ("val", 1)  # the one held-out validation image
    assert (run_dir(env) / "eval_val" / "val.json").exists()
    assert not env["docs"].exists()  # no docs/results, docs/runs or results.md
    assert json.loads((run_dir(env) / "summary.json").read_text())["test"] is None
    evaluate(env)  # a dry run does not use up the one-time test read


def test_last_checkpoint_can_be_evaluated(env):
    assert evaluate(env, checkpoint="last")["checkpoint"] == "last.pth"


def test_checkpoint_from_another_run_is_rejected(env):
    other = env["base"] / "runs" / "other"
    other.mkdir()
    shutil.copy(run_dir(env) / "best.pth", other / "best.pth")
    shutil.copy(run_dir(env) / "summary.json", other / "summary.json")
    with pytest.raises(ValueError, match="belongs to run"):
        evaluate_run(other, docs_dir=env["docs"], **env["kw"])


def test_missing_density_maps_give_an_actionable_error(env):
    shutil.rmtree(env["base"] / "processed" / "part_A" / "test_data")
    with pytest.raises(FileNotFoundError, match=r"crowd\.data\.build"):
        evaluate(env)


def test_worst_indices_orders_by_absolute_error():
    assert worst_indices([10, 50, 31, 0], [10, 0, 30, 20], k=3) == [1, 3, 2]
    assert worst_indices([1.0], [1.0], k=10) == [0]


def test_load_model_roundtrips_weights_and_returns_eval_mode(env):
    model, meta = load_model(run_dir(env) / "best.pth")
    saved = load_checkpoint(run_dir(env) / "best.pth")
    assert not model.training and meta["run_id"] == "part_A-t"
    assert all(
        torch.equal(a, b)
        for a, b in zip(model.state_dict().values(), saved["model"].values(), strict=True)
    )


def test_load_model_refuses_checkpoints_with_different_preprocessing(env, tmp_path):
    ckpt = load_checkpoint(run_dir(env) / "best.pth")
    ckpt["meta"]["preprocess"]["mean"] = [0.5, 0.5, 0.5]
    ckpt["meta"]["preprocess"]["stride"] = 16
    bad = tmp_path / "bad.pth"
    model, _ = load_model(run_dir(env) / "best.pth")
    save_checkpoint(bad, model=model, meta=ckpt["meta"])
    with pytest.raises(ValueError, match=r"mean.*stride"):
        load_model(bad)
