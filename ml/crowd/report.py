"""Plots and the generated `docs/results.md`. Uses matplotlib's object API (no pyplot), so
there is no global figure state and no display backend to configure."""

from __future__ import annotations

from pathlib import Path

from matplotlib.figure import Figure
from PIL import Image

from crowd.viz import density_to_heatmap, overlay_heatmap


def plot_scatter(pred: list[float], truth: list[float], title: str, path: Path) -> None:
    """Predicted vs true count per image, with the ideal y = x line."""
    fig = Figure(figsize=(5.5, 5.5), layout="constrained")
    ax = fig.subplots()
    ax.scatter(truth, pred, s=14, alpha=0.7)
    top = max(max(truth), max(pred)) * 1.05
    ax.plot([0, top], [0, top], "k--", lw=1, label="ideal")
    ax.set(xlim=(0, top), ylim=(0, top), xlabel="true count", ylabel="predicted count")
    ax.set_title(title)
    ax.set_aspect("equal")
    ax.legend(loc="upper left")
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path, dpi=110)


def plot_worst_gallery(rows: list[dict], title: str, path: Path) -> None:
    """One row per image: original | ground-truth density | predicted density | overlay.

    Each row dict: name, image (uint8 HxWx3), gt, pred (density maps cropped to the image),
    gt_count, pred_count. Ground truth and prediction share one colour scale per row.
    """
    fig = Figure(figsize=(12, 2.6 * len(rows)), layout="constrained")
    axes = fig.subplots(len(rows), 4, squeeze=False)
    for ax_row, r in zip(axes, rows, strict=True):
        size, vmax = r["image"].shape[:2], max(r["gt"].max(), r["pred"].max())
        panels = [
            (r["image"], f"{r['name']}"),
            (density_to_heatmap(r["gt"], size, vmax)[0], f"ground truth: {r['gt_count']:.0f}"),
            (density_to_heatmap(r["pred"], size, vmax)[0], f"predicted: {r['pred_count']:.0f}"),
            (overlay_heatmap(r["image"], r["pred"])[0], "prediction overlay"),
        ]
        for ax, (img, label) in zip(ax_row, panels, strict=True):
            ax.imshow(img)
            ax.set_title(label, fontsize=9)
            ax.axis("off")
    fig.suptitle(title)
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path, dpi=55)
    _shrink_png(path)


def _shrink_png(path: Path) -> None:
    """Re-save a photo-heavy plot with a 256-colour palette: about a third of the size, so the
    gallery stays well under the 1 MB limit the repo's pre-commit hook enforces."""
    with Image.open(path) as im:
        small = im.convert("RGB").quantize(256, method=Image.Quantize.MEDIANCUT)
    small.save(path, optimize=True)


def _fmt(x: float | None, nd: int = 1) -> str:
    return "-" if x is None else f"{x:.{nd}f}"


def render_results_md(results: list[dict]) -> str:
    """Render `docs/results.md` from per-part result dicts (see `evaluate.build_result`).

    Everything here comes from measured data; no number is typed by hand.
    """
    out = [
        "# Results",
        "",
        "<!-- Generated by `python -m crowd.evaluate`. Do not edit by hand. -->",
        "",
        "Test-set results of each part's selected checkpoint, read once. The acceptance bar is "
        "from `docs/training.md`; the published figures are CSRNet (Li et al., CVPR 2018), "
        "for reference only.",
        "",
    ]
    if not results:
        return "\n".join([*out, "_No test results yet._", ""])
    out += [
        "## Summary",
        "",
        "| Part | Run | Images | MAE | RMSE | Bar (MAE / RMSE) | Verdict | Paper (MAE / RMSE) |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for r in sorted(results, key=lambda r: r["part"]):
        a, p = r["acceptance"], r["published"]
        out.append(
            f"| {r['part'][-1]} | [`{r['run_id']}`](runs/{r['run_id']}.json) | {r['n']} | "
            f"{r['mae']:.1f} | {r['rmse']:.1f} | {a['mae_bar']:.0f} / {a['rmse_bar']:.0f} | "
            f"{'met' if a['passed'] else '**missed**'} | {p['mae']} / {p['rmse']} |"
        )
    for r in sorted(results, key=lambda r: r["part"]):
        part = r["part"]
        out += [
            "",
            f"## Part {part[-1]}",
            "",
            f"Checkpoint `{r['checkpoint']}` (epoch {r['epoch']}, `{r['model_version']}`), "
            f"git `{r['git_sha']}`, dataset hash `{r['dataset_manifest_sha'][:12]}`, "
            f"evaluated {r['evaluated_at']}.",
            "",
            "### Error by ground-truth count",
            "",
            "| Count | Images | MAE | RMSE | Bias (pred - true) |",
            "|---|---|---|---|---|",
        ]
        for b in r["buckets"]:
            cells = [b["label"], b["n"], _fmt(b["mae"]), _fmt(b["rmse"]), _fmt(b["bias"])]
            out.append("| " + " | ".join(map(str, cells)) + " |")
        heading = "Diagnosis" if not r["acceptance"]["passed"] else "Error analysis"
        out += ["", f"### {heading}", ""] + [f"- {line}" for line in r["diagnosis"]]
        out += [
            "",
            "### Predicted vs true count",
            "",
            f"![{part} scatter](results/{part}-scatter.png)",
            "",
            f"### The {len(r['worst'])} worst images",
            "",
            "| Image | True | Predicted | Error |",
            "|---|---|---|---|",
        ]
        out += [
            f"| {w['image']} | {w['truth']:.0f} | {w['pred']:.0f} | {w['error']:+.0f} |"
            for w in r["worst"]
        ]
        out += ["", f"![{part} worst images](results/{part}-worst10.png)"]
    return "\n".join([*out, ""])
